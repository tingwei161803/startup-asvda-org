# --- 總統獎 / 院長獎 9 組 (name -> award, city, prize_twd) ----------------
# president = 總統獎 (1,000 萬), premier = 院長獎 (600 萬)
WINNERS = [
    ("艾斯創生醫股份有限公司", "president", "臺北市"),
    ("星相科技股份有限公司", "president", "新竹市"),
    ("展興生物科技股份有限公司", "president", "臺中市"),
    ("日日好食股份有限公司", "premier", "臺北市"),
    ("先勁智能有限公司", "premier", "臺北市"),
    ("亞洲準譯股份有限公司", "premier", "新北市"),
    ("原子精製股份有限公司", "premier", "臺南市"),
    ("皓準科技股份有限公司", "premier", "臺中市"),
    ("豐漁水產養殖有限公司", "premier", "雲林縣"),
]
PRIZE = {"president": 1000, "premier": 600}


def build():
    name_to_id = {r[1]: r[0] for r in ROWS}

    # winners join by name -> id ; collect award + city
    win_info = {}
    for name, award, city in WINNERS:
        if name not in name_to_id:
            raise SystemExit(f"WINNER not found in 100-list by name: {name}")
        win_info[name_to_id[name]] = {"award": award, "city": city}

    items = []
    for (cid, name, cat_zh, kind_zh, region_zh) in ROWS:
        is_team = kind_zh == "團隊"
        if cid in win_info:
            stage = "winner"
        elif cid in FINALIST_IDS:
            stage = "final"
        else:
            stage = "semi"

        item = {
            "id": cid,
            "slug": cid.lower(),
            "name": name,
            "category": CATS[cat_zh],
            "category_zh": cat_zh,
            "type": "team" if is_team else "company",
            "region": "non-metro" if region_zh == "非六都" else "metro",
            "region_zh": region_zh,
            "stage": stage,
        }
        if cid in win_info:
            item["award"] = win_info[cid]["award"]
            item["city"] = win_info[cid]["city"]
            item["prize_twd"] = PRIZE[win_info[cid]["award"]]
        items.append(item)

    # ---- validate against the published statistics ----
    n = len(items)
    assert n == 100, f"expected 100 items, got {n}"
    by_kind = Counter(i["type"] for i in items)
    assert by_kind["company"] == 81, by_kind
    assert by_kind["team"] == 19, by_kind
    by_cat = Counter(i["category_zh"] for i in items)
    assert by_cat["前瞻科技組"] == 31, by_cat
    assert by_cat["消費生活組"] == 38, by_cat
    assert by_cat["綠色永續組"] == 31, by_cat
    by_region = Counter(i["region_zh"] for i in items)
    assert by_region["六都"] == 50 and by_region["非六都"] == 50, by_region
    by_stage = Counter(i["stage"] for i in items)
    assert by_stage["winner"] == 9, by_stage
    assert by_stage["final"] == 21, by_stage      # 30 finalists − 9 winners
    assert by_stage["semi"] == 70, by_stage       # 100 − 30
    # every finalist id must exist in the 100-list
    all_ids = {i["id"] for i in items}
    missing = FINALIST_IDS - all_ids
    assert not missing, f"finalist ids not in 100-list: {missing}"
    # unique slugs
    assert len({i["slug"] for i in items}) == 100, "slug collision"

    out = os.path.join(HERE, "raw_companies.json")
    with open(out, "w", encoding="utf-8") as f:
        json.dump(items, f, ensure_ascii=False, indent=2)
    print(f"OK  wrote {n} companies -> {out}")
    print(f"    company/team: {dict(by_kind)}")
    print(f"    category:     {dict(by_cat)}")
    print(f"    region:       {dict(by_region)}")
    print(f"    stage:        {dict(by_stage)}")


if __name__ == "__main__":
    build()
